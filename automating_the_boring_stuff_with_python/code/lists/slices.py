# Slicing is used to access indices within the array or list []
list_i = [2, 3, 1, 4]
first_val = list_i[0] 
last_val = list_i[-1] # Negative to get the last index (moving downward)
second_last_val = list_i[-2] # One step down in the array

print(f"First val = {first_val}") # equals 2
print(f"Last val = {last_val}") # equals 4
print(f"Second last val = {second_last_val}") # equals 1